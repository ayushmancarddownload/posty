import html2canvas from 'html2canvas';
import Cropper from 'cropperjs';
import 'cropperjs/dist/cropper.min.css';
import { SITE_NAME, LOGO, IMAGES, FEED_OPACITY_BOTTOM as FB, FEED_OPACITY_TOP as FT, BANNERS, FONTS, SHAPES, FILTERS } from '../config.js';

const $ = (id) => document.getElementById(id);
const show = (id) => ($(id).hidden = false);
const hide = (id) => ($(id).hidden = true);
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const pick = (a) => a[Math.floor(Math.random() * a.length)];
const AVATAR = 'data:image/svg+xml;utf8,' + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" fill="#d1fae5"/><circle cx="50" cy="38" r="18" fill="#10b981"/><path d="M14 100c4-28 22-38 36-38s32 10 36 38z" fill="#10b981"/></svg>');
const KEY = 'aestheticUser';

let user = {
  name: 'Aesthetic Creator', extra: 'Poster Artist', contact: '', pic: AVATAR,
  socials: { visible: true, insta: { val: '', visible: true }, twitter: { val: '', visible: true }, fb: { val: '', visible: true } },
};
const save = () => { try { localStorage.setItem(KEY, JSON.stringify(user)); } catch { toast('Storage full – photo not saved'); } };
let tt;
function toast(msg) { const t = $('toast'); t.textContent = msg; t.hidden = false; clearTimeout(tt); tt = setTimeout(() => (t.hidden = true), 2200); }

/* ---------- overlay (shared by feed + editor) ---------- */
function overlay(o, edit = false) {
  const s = user.socials;
  const rows = [['insta', 'fa-instagram'], ['twitter', 'fa-twitter'], ['fb', 'fa-facebook-f']]
    .filter(([k]) => s[k].visible)
    .map(([k, i]) => `<div class="row"><i class="fa-brands ${i} w-4 text-center"></i>${s[k].val ? `<span>${esc(s[k].val)}</span>` : ''}</div>`).join('');
  const soc = s.visible && rows ? `<div class="soc" ${edit ? 'data-act="socials" role="button" tabindex="0"' : ''}><p class="text-[8px] uppercase tracking-widest opacity-80 mb-0.5">Follow me</p>${rows}</div>` : '<div class="soc"></div>';
  const bg = `linear-gradient(to top, rgba(0,0,0,${o.op}), rgba(0,0,0,${(o.op * 0.6).toFixed(2)})), ${BANNERS[o.bg]}`;
  const ed = (k) => (edit ? `data-edit="${k}" role="button" tabindex="0" style="cursor:pointer"` : '');
  return `<div class="ov theme-${o.theme}" style="background:${bg}">
    <div class="pg"><div class="pic-wrap">
      <img class="pic ${SHAPES[o.shape]}" src="${esc(o.pic)}" alt="" style="width:${o.size}px;height:${o.size}px" ${edit ? 'data-act="pickPic"' : ''} crossorigin="anonymous" />
      ${edit ? '<button class="capture-hide absolute -bottom-1 -left-1 w-6 h-6 rounded-full bg-white text-emerald-600 text-[10px] shadow" data-act="cropPic" aria-label="Adjust photo"><i class="fa-solid fa-crop"></i></button>' : ''}</div>
      <div class="ptxt ${o.font}"><h3 class="pname" ${ed('name')}>${esc(o.name)}</h3>
        <div class="det"><div class="row" ${ed('extra')}><i class="fa-solid fa-briefcase w-4 text-center"></i><span>${esc(o.extra)}</span></div>
        ${o.contact ? `<div class="row" ${ed('contact')}><i class="fa-brands fa-whatsapp w-4 text-center"></i><span>${esc(o.contact)}</span></div>` : edit ? `<div class="row capture-hide" ${ed('contact')}><i class="fa-brands fa-whatsapp w-4 text-center"></i><span>Add number</span></div>` : ''}</div></div></div>${soc}</div>`;
}
function fitNames(root = document) {
  root.querySelectorAll('.pname').forEach((el) => { let s = 20; el.style.fontSize = s + 'px'; while (el.scrollWidth > el.clientWidth && s > 11) el.style.fontSize = (s -= 1) + 'px'; });
}

/* ---------- feed ---------- */
function loadFeed() {
  const feed = $('feed');
  let imgs = IMAGES.length ? [...IMAGES] : Array.from({ length: 12 }, (_, i) => `https://picsum.photos/id/${i + 60}/600/800`);
  imgs.sort(() => Math.random() - 0.5);
  feed.innerHTML = imgs.map((url, i) => {
    const o = { theme: pick(['left', 'center', 'right']), font: pick(FONTS), bg: Math.floor(Math.random() * BANNERS.length), op: 1, size: 56, shape: 0, name: user.name, extra: user.extra, contact: user.contact, pic: user.pic };
    return `<section class="slide"><div class="card">
      <div class="capture" id="cap-${i}">
        <img class="main" src="${esc(url)}" alt="Poster ${i + 1}" loading="${i < 2 ? 'eager' : 'lazy'}" crossorigin="anonymous" data-act="edit" data-url="${esc(url)}" />
        <img class="logo" src="${LOGO}" alt="" />
        <span class="wm">Generated by ${esc(SITE_NAME)}</span>
        ${overlay(o).replace(/rgba\(0,0,0,1\), rgba\(0,0,0,0.6\)/, `rgba(0,0,0,${FB}), rgba(0,0,0,${FT})`)}
      </div>
      <div class="flex items-center justify-between p-3">
        <button data-act="edit" data-url="${esc(url)}" class="text-sm font-bold text-emerald-600"><i class="fa-solid fa-wand-magic-sparkles"></i> Tap to edit</button>
        <div class="flex gap-2">
          <button data-act="fshare" data-id="cap-${i}" aria-label="Share" class="w-10 h-10 rounded-full bg-emerald-50 text-emerald-600"><i class="fa-solid fa-share-nodes"></i></button>
          <button data-act="fdl" data-id="cap-${i}" aria-label="Download" class="w-10 h-10 rounded-full bg-emerald-500 text-white"><i class="fa-solid fa-download"></i></button>
        </div></div></div></section>`;
  }).join('');
  feed.querySelectorAll('.main').forEach((im) => { const ok = () => im.classList.add('loaded'); im.complete ? ok() : (im.onload = ok, im.onerror = ok); });
  fitNames(feed);
}

/* ---------- export ---------- */
const snap = (el, scale) => html2canvas(el, { scale, useCORS: true, allowTaint: false, backgroundColor: null, onclone: (d) => d.querySelectorAll('.capture-hide').forEach((x) => (x.style.display = 'none')) });
async function toFile(el, scale) {
  const c = await snap(el, scale);
  return new Promise((r) => c.toBlob((b) => r(new File([b], 'poster.png', { type: 'image/png' })), 'image/png'));
}
function saveFile(file) { const a = document.createElement('a'); a.href = URL.createObjectURL(file); a.download = `poster-${Date.now()}.png`; a.click(); setTimeout(() => URL.revokeObjectURL(a.href), 4000); }
async function shareEl(el) {
  try {
    const f = await toFile(el, 2);
    if (navigator.canShare?.({ files: [f] })) await navigator.share({ files: [f], title: 'My poster' });
    else { saveFile(f); toast('Sharing not supported – saved instead'); }
  } catch (e) { if (e.name !== 'AbortError') toast('Could not share. Try download.'); }
}

/* ---------- cropper ---------- */
let cropper, cropDone, cropSrc, cropIsNew;
function openCrop(src, done, isNew = false) {
  cropSrc = src; cropDone = done; cropIsNew = isNew;
  const img = $('cropImg'); cropper?.destroy();
  show('crop'); img.src = src;
  img.onload = () => { cropper = new Cropper(img, { aspectRatio: 1, viewMode: 1, dragMode: 'move', autoCropArea: 0.85, guides: false, highlight: false, cropBoxMovable: false, cropBoxResizable: false, toggleDragModeOnDblclick: false }); };
}
function closeCrop() { cropper?.destroy(); cropper = null; hide('crop'); }
function setPic(src) {
  user.pic = src; save();
  $('navPic').src = src; $('setupPic').src = src;
  if (!$('editor').hidden) { ed.pic = src; renderEd(); }
}

/* ---------- editor ---------- */
let ed = null, editKey = null;
function renderEd() {
  $('edOv').innerHTML = overlay(ed, true); fitNames($('edOv'));
  $('edImg').style.filter = '';
  document.querySelectorAll('[data-act=theme]').forEach((b) => b.setAttribute('aria-pressed', b.dataset.v === ed.theme));
  $('fontChips').querySelectorAll('button').forEach((b) => b.setAttribute('aria-pressed', b.dataset.v === ed.font));
}
function openEditor(url) {
  ed = { url, theme: 'left', font: FONTS[0], bg: 0, op: 0.8, size: 80, shape: 0, filter: 0, name: user.name, extra: user.extra, contact: user.contact, pic: user.pic };
  $('edImg').src = url; $('edLogo').src = LOGO; $('edWm').textContent = `Generated by ${SITE_NAME}`;
  $('size').value = 80; $('sizeVal').textContent = '80px'; $('opacity').value = 80; $('opVal').textContent = '80%';
  document.querySelectorAll('.panel').forEach((p) => (p.hidden = true));
  renderEd(); show('editor'); $('nav').hidden = true;
  history.pushState({ ed: 1 }, '');
}
function hideEditor() { hide('editor'); hideAll(); $('nav').hidden = false; }
function closeEditor() { history.state?.ed ? history.back() : hideEditor(); }
const hideAll = () => ['export', 'socEdit', 'txtEdit'].forEach(hide);
window.addEventListener('popstate', () => { if (!$('editor').hidden) hideEditor(); });

async function applyFilter() {
  ed.filter = (ed.filter + 1) % FILTERS.length;
  const f = FILTERS[ed.filter];
  try {
    const im = new Image(); im.crossOrigin = 'anonymous'; im.src = ed.url; await im.decode();
    const c = document.createElement('canvas'); c.width = im.naturalWidth; c.height = im.naturalHeight;
    const x = c.getContext('2d');
    if (!('filter' in x) && f !== 'none') { toast('Filters need Chrome, Edge or Firefox'); return; }
    x.filter = f; x.drawImage(im, 0, 0);
    $('edImg').src = c.toDataURL('image/jpeg', 0.92);
    toast(f === 'none' ? 'Filter: none' : `Filter ${ed.filter}/${FILTERS.length - 1}`);
  } catch { toast('This image blocks filters (CORS)'); }
}

/* ---------- profile setup ---------- */
function openSetup(editing) {
  $('fName').value = editing ? user.name : ''; $('fExtra').value = editing ? user.extra : ''; $('fContact').value = user.contact || '';
  $('fInsta').value = user.socials.insta.val; $('fTwitter').value = user.socials.twitter.val; $('fFb').value = user.socials.fb.val;
  $('fVis').checked = user.socials.visible; $('setupPic').src = user.pic; $('setupCancel').hidden = !editing;
  show('setup');
}
function saveSetup() {
  const name = $('fName').value.trim().replace(/\b\w/g, (c) => c.toUpperCase());
  if (!name) { $('fName').focus(); toast('Enter your name'); return; }
  user.name = name; user.extra = $('fExtra').value.trim() || 'Digital Creator'; user.contact = $('fContact').value.trim();
  Object.assign(user.socials, { visible: $('fVis').checked });
  user.socials.insta.val = $('fInsta').value.trim(); user.socials.twitter.val = $('fTwitter').value.trim(); user.socials.fb.val = $('fFb').value.trim();
  save(); hide('setup'); startApp(); loadFeed();
  if (!$('editor').hidden) { Object.assign(ed, { name: user.name, extra: user.extra, contact: user.contact }); renderEd(); }
}
function startApp() { show('nav'); show('feed'); $('navPic').src = user.pic; }

/* ---------- socials editor ---------- */
function syncSocToggles() {
  const s = user.socials;
  $('socAll').setAttribute('aria-pressed', s.visible);
  [['insta', 'tInsta'], ['twitter', 'tTwitter'], ['fb', 'tFb']].forEach(([k, id]) => { $(id).setAttribute('aria-pressed', s[k].visible); $(id).style.opacity = s[k].visible ? 1 : 0.45; });
}

/* ---------- actions ---------- */
const A = {
  edit: (t) => openEditor(t.dataset.url),
  fdl: async (t) => { const i = t.innerHTML; t.innerHTML = '<i class="fa-solid fa-spinner fa-spin"></i>'; try { saveFile(await toFile($(t.dataset.id), 3)); } catch { toast('Download failed. Open the poster and try Save.'); } t.innerHTML = i; },
  fshare: (t) => shareEl($(t.dataset.id)),
  profile: () => openSetup(true), saveSetup, closeSetup: () => hide('setup'),
  pickPic: () => $('file').click(),
  cropPic: () => openCrop(user.pic, setPic, false),
  cropSave: () => { if (!cropper) return; setPic(cropper.getCroppedCanvas({ width: 300, height: 300 }).toDataURL('image/png')); closeCrop(); },
  cropSkip: () => { if (cropIsNew) cropDone(cropSrc); closeCrop(); },
  closeEditor, closeExport: () => hide('export'), exportOpen: () => show('export'),
  download: async (t) => {
    const i = t.innerHTML; t.disabled = true; t.textContent = 'Saving…';
    try { let f; try { f = await toFile($('capture'), +t.dataset.v); } catch { f = await toFile($('capture'), 2); } saveFile(f); hide('export'); toast('Saved'); }
    catch { toast('Could not save. Image may block export (CORS).'); }
    t.innerHTML = i; t.disabled = false;
  },
  share: () => shareEl($('capture')),
  panel: (t) => { const p = $('p-' + t.dataset.v), was = p.hidden; document.querySelectorAll('.panel').forEach((x) => (x.hidden = true)); document.querySelectorAll('.tool').forEach((x) => x.removeAttribute('aria-pressed')); if (was) { p.hidden = false; t.setAttribute('aria-pressed', 'true'); } },
  theme: (t) => { ed.theme = t.dataset.v; renderEd(); },
  font: (t) => { ed.font = t.dataset.v; renderEd(); },
  shape: () => { ed.shape = (ed.shape + 1) % SHAPES.length; renderEd(); },
  banner: () => { ed.bg = (ed.bg + 1) % BANNERS.length; renderEd(); },
  filter: applyFilter,
  socials: () => { $('eInsta').value = user.socials.insta.val; $('eTwitter').value = user.socials.twitter.val; $('eFb').value = user.socials.fb.val; syncSocToggles(); show('socEdit'); },
  socToggle: (t) => { const s = user.socials; t.dataset.v === 'all' ? (s.visible = !s.visible) : (s[t.dataset.v].visible = !s[t.dataset.v].visible); syncSocToggles(); if (ed) renderEd(); },
  closeSoc: () => hide('socEdit'),
  saveSoc: () => { user.socials.insta.val = $('eInsta').value.trim(); user.socials.twitter.val = $('eTwitter').value.trim(); user.socials.fb.val = $('eFb').value.trim(); save(); hide('socEdit'); renderEd(); loadFeed(); },
  closeTxt: () => hide('txtEdit'),
  saveTxt: () => { if (editKey) ed[editKey] = $('txtIn').value; hide('txtEdit'); renderEd(); },
  install: async () => { if (!deferred) return; deferred.prompt(); await deferred.userChoice; deferred = null; hide('install'); },
  closeInstall: () => hide('install'),
};
document.addEventListener('click', (e) => {
  const t = e.target.closest('[data-act]');
  if (t) { e.stopPropagation(); A[t.dataset.act]?.(t); return; }
  const k = e.target.closest('[data-edit]');
  if (k && ed) { editKey = k.dataset.edit; $('txtIn').value = ed[editKey]; show('txtEdit'); $('txtIn').focus(); }
});
document.addEventListener('keydown', (e) => { if (e.key === 'Enter' && e.target.matches('[role=button]')) e.target.click(); if (e.key === 'Escape') { if (!$('crop').hidden) closeCrop(); else if (!$('editor').hidden) closeEditor(); } });

$('fontChips').innerHTML = FONTS.map((f) => `<button class="chip ${f}" data-act="font" data-v="${f}">${f.replace('font-', '').replace(/^./, (c) => c.toUpperCase())}</button>`).join('');
$('size').addEventListener('input', (e) => { ed.size = +e.target.value; $('sizeVal').textContent = e.target.value + 'px'; renderEd(); });
$('opacity').addEventListener('input', (e) => { ed.op = e.target.value / 100; $('opVal').textContent = e.target.value + '%'; renderEd(); });
$('file').addEventListener('change', (e) => {
  const f = e.target.files[0]; e.target.value = '';
  if (!f) return;
  const r = new FileReader(); r.onload = () => openCrop(r.result, setPic, true); r.readAsDataURL(f);
});

