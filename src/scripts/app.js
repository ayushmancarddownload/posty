/* ---------- boot ---------- */
try {
  const s = JSON.parse(localStorage.getItem(KEY));
  if (s) {
    const sc = s.socials || {};
    const norm = (v) => (typeof v === 'string' ? { val: v, visible: true } : { val: v?.val || '', visible: v?.visible !== false });
    user = { ...user, ...s, pic: s.pic || AVATAR, socials: { visible: sc.visible !== false, insta: norm(sc.insta), twitter: norm(sc.twitter), fb: norm(sc.fb) } };
    startApp(); loadFeed();
  } else openSetup(false);
} catch { openSetup(false); }
